export type HoningDamageStep = {
    tier: HoningTier
    gearType: HoningGearType
    targetLevel: number
    damageGainPercent: number
}

export type HoningDamageRule = {
    tier: HoningTier
    gearType: HoningGearType
    minTargetLevel: number
    maxTargetLevel: number
    damageGainPercent: number
    sourceStatus: 'provisional'
}

export function getHoningDamageGain(
    tier: HoningTier,
    gearType: HoningGearType,
    targetLevel: number
): number | null {
    const rule = HONING_DAMAGE_RULES.find(
        rule =>
            rule.tier === tier &&
            rule.gearType === gearType &&
            targetLevel >= rule.minTargetLevel &&
            targetLevel <= rule.maxTargetLevel
    )

    return rule?.damageGainPercent ?? null
}

